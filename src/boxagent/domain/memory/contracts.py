"""Ports owned by the Memory bounded context."""

from collections.abc import Mapping
from typing import Any, Protocol

from boxagent.domain.memory.models import MemoryIngestionJob

type BackendRecord = dict[str, Any]


class MemoryLog(Protocol):
    def __call__(self, event: str, /, **data: object) -> None: ...


class MemoryUnavailable(RuntimeError):
    """The configured memory backend is unavailable or violated its protocol."""


class MemoryBackend(Protocol):
    async def health(self) -> BackendRecord: ...
    async def remember(self, observations: list[BackendRecord]) -> BackendRecord: ...
    async def remember_narrative(self, checkpoint: BackendRecord, *,
                                 metadata: BackendRecord | None = None) -> BackendRecord: ...
    async def query(self, question: str, *, top_k: int = 5,
                    mode: str = "deep") -> BackendRecord: ...
    async def inspect(self, *, query: str = "", selected_id: str | None = None,
                      node_limit: int = 100, edge_limit: int = 200) -> BackendRecord: ...
    async def forget(self, memory_ids: list[str]) -> BackendRecord: ...
    async def save(self) -> BackendRecord: ...
    async def close(self) -> None: ...


class MemoryJobStore(Protocol):
    async def start(self) -> None: ...
    async def enqueue_job(self, *, session_id: str, interaction_id: str,
                          source_hash: str, admission_version: str) \
            -> MemoryIngestionJob: ...
    async def jobs(self, *, statuses: set[str] | None = None) \
            -> list[MemoryIngestionJob]: ...
    async def update_job(self, job: MemoryIngestionJob) -> MemoryIngestionJob: ...


class ProfileConstructor(Protocol):
    async def propose(self, observation: str,
                      current_fields: Mapping[str, BackendRecord]) -> list[BackendRecord]: ...


class ProfileProjection(Protocol):
    async def observe(self, node: BackendRecord) -> object: ...

    async def forget(self, memory_id: str) -> object: ...
